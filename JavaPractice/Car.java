public class Car{
    String model;
    String color;
    int price;
    Car(String model, String color, int price){
        this.model = model;
        this.color = color;
        this.price = price;
    }
String getModel()
{
    return this.model;

}
String getColor()
{
    return this.color;

}
int getPrice()
{
    return this.price;

}
}
